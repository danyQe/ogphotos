"""Generate THIRD_PARTY_LICENSES.md (run `--check` in CI to detect drift).

Usage: uv run python scripts/gen_third_party.py [--check]

Developer/CI script, not runtime: it uses the network (PyPI JSON API), which the app
itself never does.

Determinism: the package list and versions come from the lockfile
(`uv export --no-dev --no-hashes --no-emit-project --frozen`), with environment markers
evaluated (via `packaging`, a transitive dependency) for one fixed target (linux, x86_64,
Python 3.12) rather than the host. That drops host-only packages, dev-only packages and
the project itself. License names and URLs are read from PyPI for each exact pinned
version (metadata for a released version is immutable), so the output does not depend on
the host OS, Python version or installed environment. Network errors fail loudly.
Model names and licenses are read from app/models_registry.py so they cannot drift.
"""

from __future__ import annotations

import argparse
import json
import re
import subprocess
import sys
import urllib.request
from pathlib import Path

from packaging.markers import Marker

ROOT = Path(__file__).resolve().parent.parent
OUTPUT = ROOT / "THIRD_PARTY_LICENSES.md"
HTMX_JS = ROOT / "app" / "static" / "htmx.min.js"
UV_VERSION_FILE = ROOT / "packaging" / "uv-version.txt"
PROJECT_NAME = "ogphotos"
TARGET_ENV = {
    "sys_platform": "linux",
    "platform_machine": "x86_64",
    "python_full_version": "3.12.0",
    "python_version": "3.12",
    "implementation_name": "cpython",
    "platform_system": "Linux",
    "os_name": "posix",
}

sys.path.insert(0, str(ROOT))
from app.models_registry import EMBED_MODEL_ID, FACE_MODEL_ID, get_spec  # noqa: E402

HEADER = """# Third-party licenses

OGphotos is MIT licensed (see `LICENSE`). It depends on the following Python packages,
which keep their own licenses. This file is generated by `scripts/gen_third_party.py`;
do not edit by hand.

## Python packages

"""


def _norm(name: str) -> str:
    return re.sub(r"[-_.]+", "-", name).lower()


def locked_packages() -> dict[str, str]:
    """Runtime packages from the lockfile for TARGET_ENV: normalized name -> version."""
    out = subprocess.run(
        ["uv", "export", "--no-dev", "--no-hashes", "--no-emit-project", "--frozen"],
        cwd=ROOT,
        check=True,
        capture_output=True,
        text=True,
    ).stdout
    pkgs: dict[str, str] = {}
    for line in out.splitlines():
        if not line.strip() or line.lstrip().startswith("#"):
            continue
        m = re.match(r"^([A-Za-z0-9._-]+)==([^\s;]+)\s*(?:;\s*(.*))?$", line)
        if not m:
            raise SystemExit(f"Unrecognized line in uv export output: {line!r}")
        name, version, marker = m.groups()
        if _norm(name) == PROJECT_NAME:
            continue
        if marker and not Marker(marker).evaluate(TARGET_ENV):
            continue
        pkgs[_norm(name)] = version
    return pkgs


_PYPI_CACHE: dict[tuple[str, str], dict] = {}
_URL_KEYS = ("homepage", "source", "repository")


def fetch_pypi_info(name: str, version: str) -> dict:
    """PyPI `info` block for an exact release (local version suffix like +cpu is dropped)."""
    version = version.split("+", 1)[0]
    key = (name, version)
    if key not in _PYPI_CACHE:
        url = f"https://pypi.org/pypi/{name}/{version}/json"
        try:
            with urllib.request.urlopen(url, timeout=20) as resp:  # noqa: S310
                _PYPI_CACHE[key] = json.load(resp)["info"]
        except OSError as exc:
            raise SystemExit(f"Failed to fetch {url}: {exc}") from exc
    return _PYPI_CACHE[key]


def pick_license(info: dict) -> str:
    expr = (info.get("license_expression") or "").strip()
    if expr:
        return expr
    lic = (info.get("license") or "").strip()
    if lic and len(lic) <= 80 and "\n" not in lic:
        return lic
    prefix = "License :: OSI Approved :: "
    classifiers = [
        c.removeprefix(prefix) for c in info.get("classifiers") or [] if c.startswith("License :: ")
    ]
    return ", ".join(classifiers) if classifiers else "UNKNOWN"


def pick_url(info: dict, name: str) -> str:
    urls = {k.lower(): v for k, v in (info.get("project_urls") or {}).items() if v}
    for key in _URL_KEYS:
        if key in urls:
            return urls[key]
    return info.get("home_page") or f"https://pypi.org/project/{name}/"


def _cell(text: str) -> str:
    return " ".join(text.split()).replace("|", r"\|")


def packages_table() -> str:
    locked = locked_packages()
    rows = ["| Name | Version | License | URL |", "|---|---|---|---|"]
    for key in sorted(locked):
        info = fetch_pypi_info(key, locked[key])
        rows.append(
            f"| {_cell(info.get('name') or key)} | {_cell(locked[key])} "
            f"| {_cell(pick_license(info))} | {_cell(pick_url(info, key))} |"
        )
    return "\n".join(rows) + "\n"


def bundled_section() -> str:
    m = re.search(r'version:"([^"]+)"', HTMX_JS.read_text(encoding="utf-8"))
    if not m:
        raise SystemExit(f"Could not find the htmx version in {HTMX_JS}")
    version = m.group(1)
    uv_version = UV_VERSION_FILE.read_text(encoding="utf-8").strip()
    return (
        "\n## Bundled assets\n\n"
        f"- htmx {version} (`app/static/htmx.min.js`), BSD 2-Clause License, "
        "https://github.com/bigskysoftware/htmx\n"
        f"- uv {uv_version} (`bin/`), MIT OR Apache-2.0, https://github.com/astral-sh/uv "
        "(license texts in `bin/LICENSE-MIT` and `bin/LICENSE-APACHE`)\n"
    )


def models_section() -> str:
    lines = ["\n## Models (downloaded separately, not part of this project)\n"]
    lines.append(
        "OGphotos does not ship any model weights. They are downloaded on request and are "
        "covered by their own licenses.\n"
    )
    for model_id in (EMBED_MODEL_ID, FACE_MODEL_ID):
        spec = get_spec(model_id)
        lines.append(
            f"- {spec.name}: {spec.license_name}. {spec.license_summary} {spec.license_url}"
        )
    return "\n".join(lines) + "\n"


def render() -> str:
    return HEADER + packages_table() + bundled_section() + models_section()


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--check", action="store_true", help="exit 1 if the file is stale")
    args = parser.parse_args()
    text = render()
    if args.check:
        current = OUTPUT.read_text(encoding="utf-8") if OUTPUT.exists() else ""
        if current != text:
            print("THIRD_PARTY_LICENSES.md is out of date; run scripts/gen_third_party.py")
            return 1
        return 0
    OUTPUT.write_text(text, encoding="utf-8", newline="\n")
    print(f"wrote {OUTPUT}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
